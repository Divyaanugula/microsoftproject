import { useState, useEffect } from 'react';
import { Link } from 'react-router-dom';
import { FileText, AlertTriangle, CheckCircle, Lightbulb, Shield, ChevronDown, ChevronUp, Download, Copy, Check, Search, ExternalLink } from 'lucide-react';

const API_BASE = 'http://localhost:8000/api/incidents';

const PostMortem = () => {
  const [reports, setReports] = useState([]);
  const [loading, setLoading] = useState(true);
  const [expandedId, setExpandedId] = useState(null);
  const [search, setSearch] = useState('');
  const [copiedId, setCopiedId] = useState(null);

  useEffect(() => {
    const fetchReports = async () => {
      try {
        const res = await fetch(`${API_BASE}/post-mortems/all`);
        const data = await res.json();
        setReports(data);
        if (data.length > 0) {
          setExpandedId(data[0].incident_id);
        }
      } catch (err) {
        console.error('Failed to fetch post-mortems:', err);
      } finally {
        setLoading(false);
      }
    };
    fetchReports();
  }, []);

  const toggleExpand = (id) => {
    setExpandedId(expandedId === id ? null : id);
  };

  const getReportMarkdown = (report) => {
    return `# Incident Post-Mortem: ${report.title} (${report.incident_id})
**Severity:** ${report.severity}
**Resolved At:** ${report.resolved_at}

## Summary
${report.summary}

## Root Causes
${report.root_causes.map(c => `- ${c}`).join('\n')}

## Solutions Applied
${report.solutions_applied.map((s, i) => `${i + 1}. ${s}`).join('\n')}

## Lessons Learned
${report.lessons_learned.map(l => `- ${l}`).join('\n')}

## Prevention Steps
${report.prevention_steps.map((p, i) => `${i + 1}. ${p}`).join('\n')}

---
*Generated by OpsEcho Incident Response Agent*
`;
  };

  const handleDownloadMarkdown = (report) => {
    const md = getReportMarkdown(report);
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `PostMortem_${report.incident_id}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handleCopyMarkdown = (report) => {
    const md = getReportMarkdown(report);
    navigator.clipboard.writeText(md);
    setCopiedId(report.incident_id);
    setTimeout(() => setCopiedId(null), 2500);
  };

  const filtered = reports.filter(r =>
    !search ||
    r.title.toLowerCase().includes(search.toLowerCase()) ||
    r.incident_id.toLowerCase().includes(search.toLowerCase()) ||
    r.summary.toLowerCase().includes(search.toLowerCase())
  );

  return (
    <div className="post-mortem">
      <div className="page-header">
        <div>
          <h1>Post-Mortem Reports</h1>
          <p>Auto-generated analysis reports for resolved incidents.</p>
        </div>
      </div>

      {/* Search Bar */}
      <div style={{ marginBottom: '20px', maxWidth: '360px', position: 'relative' }}>
        <Search size={16} style={{ position: 'absolute', left: '12px', top: '50%', transform: 'translateY(-50%)', color: 'var(--text-muted)' }} />
        <input
          type="text"
          className="form-control"
          placeholder="Search post-mortems..."
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          style={{ paddingLeft: '36px' }}
        />
      </div>

      {loading ? (
        <div className="loading-spinner">
          <div className="spinner"></div>
          <span className="loading-text">Loading reports...</span>
        </div>
      ) : filtered.length === 0 ? (
        <div className="card empty-state">
          <FileText size={48} />
          <h3>No post-mortems found</h3>
          <p>Resolve an incident with AI analysis to automatically generate a post-mortem report.</p>
        </div>
      ) : (
        <div style={{ display: 'flex', flexDirection: 'column', gap: '16px' }}>
          {filtered.map(report => (
            <div key={report.incident_id} className="post-mortem-card" onClick={() => toggleExpand(report.incident_id)}>
              <div className="pm-header">
                <div>
                  <div style={{ display: 'flex', alignItems: 'center', gap: '10px' }}>
                    <span className="pm-id">{report.incident_id}</span>
                    <Link
                      to={`/incidents/${report.incident_id}`}
                      onClick={(e) => e.stopPropagation()}
                      style={{ fontSize: '12px', color: 'var(--accent-blue)', display: 'inline-flex', alignItems: 'center', gap: '3px' }}
                      title="View Incident Record"
                    >
                      <ExternalLink size={12} />
                    </Link>
                  </div>
                  <div className="pm-title">{report.title}</div>
                  <div style={{ display: 'flex', gap: '8px', marginTop: '8px' }}>
                    <span className={`badge badge-${report.severity.toLowerCase()}`}>{report.severity}</span>
                    <span className="badge badge-resolved">Resolved</span>
                  </div>
                </div>
                <div style={{ display: 'flex', alignItems: 'center', gap: '12px' }}>
                  <span style={{ fontSize: '12px', color: 'var(--text-muted)' }}>{report.resolved_at}</span>
                  {expandedId === report.incident_id ? <ChevronUp size={18} color="var(--text-muted)" /> : <ChevronDown size={18} color="var(--text-muted)" />}
                </div>
              </div>

              {expandedId === report.incident_id && (
                <div style={{ marginTop: '20px', borderTop: '1px solid var(--border-color)', paddingTop: '20px' }} onClick={e => e.stopPropagation()}>
                  {/* Action Toolbar */}
                  <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '8px', marginBottom: '16px' }}>
                    <button
                      className="btn btn-ghost"
                      style={{ padding: '4px 10px', fontSize: '12px' }}
                      onClick={() => handleCopyMarkdown(report)}
                    >
                      {copiedId === report.incident_id ? (
                        <>
                          <Check size={13} color="var(--accent-success)" /> Copied!
                        </>
                      ) : (
                        <>
                          <Copy size={13} /> Copy Markdown
                        </>
                      )}
                    </button>
                    <button
                      className="btn btn-ghost"
                      style={{ padding: '4px 10px', fontSize: '12px' }}
                      onClick={() => handleDownloadMarkdown(report)}
                    >
                      <Download size={13} /> Download .md
                    </button>
                  </div>

                  {/* Summary */}
                  <div className="pm-detail-section">
                    <p style={{ fontSize: '14px', color: 'var(--text-secondary)', lineHeight: '1.7' }}>
                      {report.summary}
                    </p>
                  </div>

                  {/* Root Causes */}
                  <div className="pm-detail-section">
                    <h3 style={{ color: 'var(--accent-danger)' }}>
                      <AlertTriangle size={15} /> Root Causes
                    </h3>
                    <ul>
                      {report.root_causes.map((cause, i) => (
                        <li key={i}>{cause}</li>
                      ))}
                    </ul>
                  </div>

                  {/* Solutions Applied */}
                  <div className="pm-detail-section">
                    <h3 style={{ color: 'var(--accent-success)' }}>
                      <CheckCircle size={15} /> Solutions Applied
                    </h3>
                    <ol>
                      {report.solutions_applied.map((sol, i) => (
                        <li key={i}>{sol}</li>
                      ))}
                    </ol>
                  </div>

                  {/* Lessons Learned */}
                  <div className="pm-detail-section">
                    <h3 style={{ color: 'var(--accent-warning)' }}>
                      <Lightbulb size={15} /> Lessons Learned
                    </h3>
                    <ul>
                      {report.lessons_learned.map((lesson, i) => (
                        <li key={i}>{lesson}</li>
                      ))}
                    </ul>
                  </div>

                  {/* Prevention */}
                  <div className="pm-detail-section" style={{ marginBottom: 0 }}>
                    <h3 style={{ color: 'var(--accent-purple)' }}>
                      <Shield size={15} /> Prevention Steps
                    </h3>
                    <ol>
                      {report.prevention_steps.map((step, i) => (
                        <li key={i}>{step}</li>
                      ))}
                    </ol>
                  </div>
                </div>
              )}
            </div>
          ))}
        </div>
      )}
    </div>
  );
};

export default PostMortem;
